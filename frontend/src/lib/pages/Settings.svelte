<script lang="ts">
  import { About, Banner, Button, Modal, PageHeader, Select, SettingsRow, SettingsSection, Toggle } from '@etzianco/ui';
  import { onMount } from 'svelte';

  import { available, DEFAULT_CHOICE, eraseFailureText, erasedItems, folderName, targetsOf, type EraseChoice } from '../erase';
  import { formatBytes } from '../export';
  import { appInfo, eraseInventory, eraseProjectData, type EraseInventory } from '../ipc/app';
  import type { IpcError } from '../ipc/invoke';
  import { project } from '../stores/project.svelte';

  import { DangerZone } from '../legal-ux';
  import { getLocale, t } from '../i18n';
  import { applyDensity, applyLanguage, applyTheme, eraseLocalData, settings, type Density, type Language, type ThemePreference } from '../stores/settings.svelte';

  // Generated by `ez legal gen`; rebuilt with the app. Drafts until a lawyer reviews the templates.
  const docs: Record<string, Record<string, string>> = {
    'fr-CA': {
      privacy: Object.values(import.meta.glob('../../../../legal/generated/fr-CA/privacy-policy.md', { query: '?raw', import: 'default', eager: true }))[0] as string,
      terms: Object.values(import.meta.glob('../../../../legal/generated/fr-CA/terms-of-use.md', { query: '?raw', import: 'default', eager: true }))[0] as string
    },
    en: {
      privacy: Object.values(import.meta.glob('../../../../legal/generated/en/privacy-policy.md', { query: '?raw', import: 'default', eager: true }))[0] as string,
      terms: Object.values(import.meta.glob('../../../../legal/generated/en/terms-of-use.md', { query: '?raw', import: 'default', eager: true }))[0] as string
    }
  };

  let version = $state('');
  let openDoc = $state<'privacy' | 'terms' | null>(null);

  onMount(() => {
    appInfo().then((i) => (version = i.version)).catch(() => {});
  });

  const languages = $derived([
    { value: 'system', label: t('settings-language-system') },
    { value: 'fr-CA', label: t('settings-language-fr-ca') },
    { value: 'en', label: t('settings-language-en') }
  ]);
  const themes = $derived([
    { value: 'auto', label: t('settings-theme-system') },
    { value: 'light', label: t('settings-theme-light') },
    { value: 'dark', label: t('settings-theme-dark') }
  ]);
  const densities = $derived([
    { value: 'comfortable', label: t('settings-density-comfortable') },
    { value: 'compact', label: t('settings-density-compact') }
  ]);
  // Erase all data (ADR-026): the user chooses what goes; the open folder's items only
  // when a folder is open.
  const root = $derived(project.root);
  let inventory = $state<EraseInventory | null>(null);
  let choice = $state<EraseChoice>({ ...DEFAULT_CHOICE });
  let eraseError = $state<string | null>(null);
  let eraseNotice = $state<string | null>(null);
  const can = $derived(available(inventory));
  const items = $derived(erasedItems(choice, inventory, root));
  const deleted = $derived(items.length ? items : [t('erase-nothing-chosen')]);

  async function loadInventory(of: string) {
    if (!of) {
      inventory = null;
      return;
    }
    try {
      const inv = await eraseInventory(of);
      if (project.root === of) inventory = inv;
    } catch {
      if (project.root === of) inventory = null;
    }
  }

  $effect(() => {
    void loadInventory(root);
  });

  async function erase() {
    eraseError = null;
    eraseNotice = null;
    const targets = targetsOf(choice, inventory);
    const any = targets.project_data || targets.exports || targets.quarantine || targets.copies;
    if (root && any) {
      try {
        const report = await eraseProjectData(root, targets);
        if (report.copies_kept > 0) eraseNotice = t('erase-done-copies-kept', { count: report.copies_kept });
      } catch (err) {
        const e = err as IpcError;
        eraseError = e.kind === 'erase' ? eraseFailureText((e.args?.reason as string | undefined) ?? null) : t('error-erase', { reason: 'other' });
        await loadInventory(root);
        throw err;
      }
    }
    if (choice.settings) eraseLocalData();
    await loadInventory(root);
  }
  const year = $derived(new Date().getFullYear());
  const title = $derived(openDoc === 'privacy' ? t('legal-privacy-policy') : t('legal-terms-of-use'));
</script>

<div class="app-page">
  <PageHeader title={t('settings-title')} />

  <SettingsSection title={t('settings-section-language')}>
    <Select label={t('settings-language-label')} placeholder="" value={settings.language} options={languages} onchange={(e: Event) => applyLanguage((e.target as HTMLSelectElement).value as Language)} />
  </SettingsSection>

  <SettingsSection title={t('settings-section-appearance')}>
    <Select label={t('settings-theme-label')} placeholder="" value={settings.theme} options={themes} onchange={(e: Event) => applyTheme((e.target as HTMLSelectElement).value as ThemePreference)} />
    <Select label={t('settings-density-label')} placeholder="" value={settings.density} options={densities} onchange={(e: Event) => applyDensity((e.target as HTMLSelectElement).value as Density)} />
  </SettingsSection>

  <SettingsSection title={t('settings-section-privacy')} description={t('settings-privacy-description')}>
    <SettingsRow label={t('legal-privacy-policy')}><Button variant="secondary" onclick={() => (openDoc = 'privacy')}>{t('privacy-policy-open')}</Button></SettingsRow>
    <SettingsRow label={t('legal-terms-of-use')}><Button variant="secondary" onclick={() => (openDoc = 'terms')}>{t('privacy-policy-open')}</Button></SettingsRow>
  </SettingsSection>

  <About
    name={t('app-name')}
    version={version ? t('about-version', { version }) : ''}
    versionLabel=""
    endorsedBy={t('about-endorsed-by')}
    copyright={t('about-copyright', { year: String(year), company: t('company-name') })}
  />
  <p class="app-notice">{t('about-ffmpeg-notice')}</p>

  <SettingsSection title={t('erase-section')} description={t('erase-section-description')}>
    <SettingsRow label={t('erase-choice-settings')} hint={t('erase-item-settings')}>
      <Toggle bind:checked={choice.settings} label={t('erase-choice-settings')} />
    </SettingsRow>
    {#if root}
      <SettingsRow
        label={t('erase-choice-project')}
        hint={can.project_data && inventory ? t('erase-choice-project-hint', { folder: folderName(root), size: formatBytes(inventory.project_data.bytes) }) : t('erase-choice-empty')}
      >
        <Toggle bind:checked={choice.project_data} disabled={!can.project_data} label={t('erase-choice-project')} />
      </SettingsRow>
      <SettingsRow
        label={t('erase-choice-exports')}
        hint={can.exports && inventory ? t('erase-choice-exports-hint', { count: inventory.exports.files, size: formatBytes(inventory.exports.bytes) }) : t('erase-choice-empty')}
      >
        <Toggle bind:checked={choice.exports} disabled={!can.exports} label={t('erase-choice-exports')} />
      </SettingsRow>
      <SettingsRow
        label={t('erase-choice-copies')}
        hint={can.copies && inventory ? t('erase-choice-copies-hint', { count: inventory.copies.files, size: formatBytes(inventory.copies.bytes), folders: inventory.copies.folders.join(', ') }) : t('erase-choice-empty')}
      >
        <Toggle bind:checked={choice.copies} disabled={!can.copies} label={t('erase-choice-copies')} />
      </SettingsRow>
      {#if inventory && inventory.copies.moved > 0}
        <p class="app-notice">{t('erase-choice-copies-moved', { count: inventory.copies.moved })}</p>
      {/if}
      <SettingsRow
        label={t('erase-choice-quarantine')}
        hint={can.quarantine && inventory ? t('erase-choice-quarantine-hint', { count: inventory.quarantine.files, size: formatBytes(inventory.quarantine.bytes) }) : t('erase-choice-empty')}
      >
        <Toggle bind:checked={choice.quarantine} disabled={!can.quarantine} label={t('erase-choice-quarantine')} />
      </SettingsRow>
    {:else}
      <p class="app-notice">{t('erase-no-project')}</p>
    {/if}
    {#if eraseError}
      <Banner tone="error" text={eraseError} ondismiss={() => (eraseError = null)} dismissLabel={t('clean-dismiss')} />
    {:else if eraseNotice}
      <Banner tone="info" text={eraseNotice} ondismiss={() => (eraseNotice = null)} dismissLabel={t('clean-dismiss')} />
    {/if}
  </SettingsSection>

  <DangerZone kind="local-data" {t} {deleted} ondelete={erase} />
</div>

<Modal open={openDoc !== null} {title} onclose={() => (openDoc = null)}>
  <pre class="app-doc" lang={getLocale()}>{openDoc ? docs[getLocale()][openDoc] : ''}</pre>
</Modal>

<style>
  .app-notice {
    font-size: var(--ez-fs-sm);
    color: var(--ez-color-text-muted);
    margin: 0;
  }
</style>
